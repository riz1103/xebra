const MESSAGES: Record<Locale, Record<MessageKey, string>> = {
  en: { ...en, ...staffEn },
  fil: { ...fil, ...staffFil },
};
const STORAGE_KEY = "xevra-locale";

interface LocaleValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Record<string, string | number>) => string;
}

const LocaleContext = createContext<LocaleValue | null>(null);

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((stored) => {
        if (stored === "en" || stored === "fil") setLocaleState(stored);
      })
      .catch(() => undefined);
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    AsyncStorage.setItem(STORAGE_KEY, next).catch(() => undefined);
  }, []);

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => {
      const template = MESSAGES[locale][key] ?? MESSAGES.en[key];
      if (!vars) return template;
      return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
    },
    [locale]
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used within LocaleProvider");
  return value;
}

export function useT() {
  return useLocale().t;
}

export function roleLabel(t: LocaleValue["t"], role: string | undefined): string {
  if (role === "admin") return t("role.admin");
  if (role === "proctor") return t("role.proctor");
  if (role === "user" || role === "examinee" || !role) return t("role.examinee");
  return role;
}
