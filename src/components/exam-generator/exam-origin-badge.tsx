import { PenLine, Sparkles } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import type { ExamOrigin } from "@/types";

export const EXAM_ORIGIN_LABELS: Record<ExamOrigin, string> = {
  ai: "AI generated",
  mixed: "AI-assisted",
  manual: "Manual",
};

const ORIGIN_TITLES: Record<ExamOrigin, string> = {
  ai: "Every question was generated by AI from uploaded material.",
  mixed: "Some questions were generated by AI; others were written or edited by hand.",
  manual: "Questions were written or imported by hand.",
};

/** Exams created before origin tagging have no origin; they predate AI generation, so they count as manual. */
export function examOrigin(origin: ExamOrigin | undefined): ExamOrigin {
  return origin ?? "manual";
}

export function ExamOriginBadge({ origin, className }: { origin: ExamOrigin | undefined; className?: string }) {
  const value = examOrigin(origin);
  const Icon = value === "manual" ? PenLine : Sparkles;
  return (
    <Badge variant={value === "manual" ? "outline" : "secondary"} className={className} title={ORIGIN_TITLES[value]}>
      <Icon className="mr-1 h-3 w-3" />
      {EXAM_ORIGIN_LABELS[value]}
    </Badge>
  );
}
